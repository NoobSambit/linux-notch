#!/usr/bin/env python3
"""Validate checkpoint records/links; optionally regenerate the owner view. Stdlib only.

This checks record structure and recorded gate prerequisites. It cannot grant owner approval,
decode/review images for an agent, prove a test actually ran, or validate product behavior.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
RECORD = ROOT / 'docs/workflow/progress.json'
STATES = ['PLANNED', 'AWAITING REFERENCES', 'REFERENCES SUBMITTED',
          'AWAITING VISUAL APPROVAL', 'READY TO IMPLEMENT', 'IMPLEMENTING',
          'TESTING', 'AWAITING OWNER TEST', 'APPROVED']
RESULTS = {'PASS', 'FAIL', 'NOT TESTED', 'NEEDS HELP'}
IMPLEMENTATION = set(STATES[4:])


def local(path):
    target = (ROOT / path).resolve()
    if not target.is_relative_to(ROOT):
        raise ValueError(f'Path escapes repository: {path}')
    return target


def overview(data):
    rows = ['# Current progress', '', '<!-- Generated by tools/workflow.py. Edit progress.json, not this view. -->', '',
            '## WHAT YOU NEED TO DO NOW', '']
    records = data['checkpoints']
    selected = data['active_checkpoint'] or data['next_checkpoint']
    current = next((c for c in records if c['id'] == selected), records[-1])
    rows += [current['next_owner_action'], '', f'Workflow: **{data["workflow_status"]}**.',
             f'Active checkpoint: **{data["active_checkpoint"] or "None — no checkpoint has started"}**.',
             (f'Next checkpoint: [{current["id"]}](checkpoints/{current["id"]}.md).' if selected else 'All checkpoints approved; publishing still requires separate permission.'), '',
             '| Checkpoint | State | References | Tasks done | Tests: pass / fail / untested / help |',
             '| --- | --- | --- | --- | --- |']
    for c in records:
        counts = Counter(t['result'] for t in c['tests'])
        ref = 'Not required'
        if c['visual']:
            ref = ('Approved ' + c['gate_a']['set_id'] if c['gate_a'] else
                   'Submitted; awaiting review/approval' if c['status'] in {'REFERENCES SUBMITTED', 'AWAITING VISUAL APPROVAL'} else
                   f'{len(c["reference_requirements"])} images needed when activated; none approved')
        done = sum(t['status'] == 'DONE' for t in c['tasks'])
        score = ' / '.join(str(counts[x]) for x in ['PASS', 'FAIL', 'NOT TESTED', 'NEEDS HELP'])
        rows.append(f'| [{c["id"]} — {c["title"]}](checkpoints/{c["id"]}.md) | {c["status"]} | {ref} | {done}/{len(c["tasks"])} | {score} |')
    rows += ['', '## Current handoff', '', f'- Codex next: {current["next_agent_action"]}',
             f'- You next: {current["next_owner_action"]}',
             f'- Waiting/blocker: {current["blocked_reason"] or "Owner authorization and approved prerequisites as described above."}',
             f'- Test version / run: {current["latest_run"] or "No runtime handoff yet."}', '',
             '## Tests and remaining work', '']
    for c in records:
        if c['id'] != current['id'] and c['status'] == 'PLANNED':
            continue
        rows += [f'### {c["id"]}', '', f'Next: {c["next_owner_action"]}', '',
                 'Remaining tasks: ' + ', '.join(t['id'] for t in c['tasks'] if t['status'] != 'DONE') + '.', '']
        owner = [t for t in c['tests'] if t['kind'] == 'owner']
        rows += [f'- **{t["id"]} {t["result"]}** — {t["title"]}' + (f' ({t["reason"]})' if t['reason'] else '') for t in owner]
        rows += ['', 'Engineering checks: ' + '; '.join(f'{t["id"]}: {t["result"]}' for t in c['tests'] if t['kind'] != 'owner') + '.',
                 f'Approval: {"Owner approved the tested run." if c["gate_b"] else "Waiting; no final owner approval recorded."}', '']
    rows += ['Codex keeps this page aligned with its [single progress record](../docs/workflow/progress.json).',
             'An image submission is not visual approval. Automated checks are not app approval.',
             'No image generation is needed for CP-00, CP-01, CP-02 or CP-10.',
             '[Start here](README.md) · [References](VISUAL_REFERENCES.md) · [Testing](TESTING.md) · [Recovery](RECOVERY.md)', '']
    return '\n'.join(rows)


def validate(data):
    errors = []

    def need(condition, message):
        if not condition:
            errors.append(message)

    records = data['checkpoints']
    ids = [c['id'] for c in records]
    need(len(ids) == 11 and len(set(ids)) == 11, 'Expected eleven unique checkpoints')
    need(data['active_checkpoint'] is None or data['active_checkpoint'] in ids, 'Invalid active checkpoint')
    need(data['next_checkpoint'] in ids or (data['next_checkpoint'] is None and all(c['status'] == 'APPROVED' for c in records)), 'Invalid next checkpoint')
    by_id = {c['id']: c for c in records}
    for i, c in enumerate(records):
        cid = c['id']
        need(cid.startswith(f'cp-{i:02}-'), f'{cid}: roadmap order changed')
        need(c['status'] in STATES, f'{cid}: invalid lifecycle')
        need(c['visual'] == (3 <= i <= 9), f'{cid}: visual classification mismatch')
        need(c['depends_on'] == ([] if i == 0 else [ids[i-1]]), f'{cid}: sequence/dependency changed')
        if c['status'] != 'PLANNED':
            authorization = c['authorization'] or {}
            need(all(authorization.get(k) for k in ['owner_quote', 'date', 'source', 'scope']), f'{cid}: authorization missing/incomplete')
            need(all(by_id[d]['status'] == 'APPROVED' for d in c['depends_on']), f'{cid}: unapproved dependency')
        for field in ['contract', 'visual_brief', 'owner_note']:
            need(local(c[field]).is_file(), f'{cid}: missing {field}')
        contract = local(c['contract']).read_text()
        brief = local(c['visual_brief']).read_text()
        owner = local(c['owner_note']).read_text()
        for heading in ['Objective', 'Prerequisites', 'Authoritative specification references',
                        'In scope and affected modules', 'Out of scope', 'Implementation tasks',
                        'Acceptance criteria and proof mapping', 'Technical risks',
                        'Automated verification', 'Runtime verification', 'Completion and approval gates']:
            need(f'## {heading}' in contract, f'{cid}: missing contract {heading}')
        need('WHAT YOU NEED TO DO NOW' in owner, f'{cid}: missing owner action')
        task_ids = [t['id'] for t in c['tasks']]
        test_ids = [t['id'] for t in c['tests']]
        need(len(set(task_ids)) == len(task_ids), f'{cid}: duplicate tasks')
        need(len(set(test_ids)) == len(test_ids), f'{cid}: duplicate tests')
        proof_ids = set(re.findall(r'\b[ARM]\d{2}\b', contract))
        need(proof_ids.issubset(set(test_ids)), f'{cid}: unknown acceptance/task proof ID')
        for task in c['tasks']:
            need(f'| {task["id"]} |' in contract, f'{cid}: undocumented task')
            need(task['status'] in {'PENDING', 'IN PROGRESS', 'DONE'}, f'{cid}: invalid task state')
            if task['status'] == 'DONE':
                need(bool(task['evidence']), f'{cid}/{task["id"]}: done without evidence')
        for test in c['tests']:
            tid = test['id']
            need(test['result'] in RESULTS, f'{cid}/{tid}: invalid test result')
            need(test['kind'] in {'automated', 'runtime', 'owner'}, f'{cid}/{tid}: invalid test kind')
            need(tid in contract, f'{cid}/{tid}: missing engineering proof mapping')
            if test['kind'] == 'owner':
                match = re.search(rf'### {tid} — .*?(?=\n### |\n## |\Z)', owner, re.S)
                need(bool(match), f'{cid}/{tid}: missing owner test')
                if match:
                    for label in ['Before starting', 'What to do', 'Expected result', 'Failure examples', 'Evidence', 'Recovery']:
                        need(f'**{label}:**' in match[0], f'{cid}/{tid}: missing {label}')
                    steps = re.findall(r'^\d+\.\s*([^\n]*)$', match[0], re.M)
                    need(bool(steps) and all(s.strip() for s in steps), f'{cid}/{tid}: empty/missing numbered steps')
            if test['result'] != 'NOT TESTED':
                need(bool(test['history']), f'{cid}/{tid}: result without history')
            if test['history']:
                need(test['history'][-1]['result'] == test['result'] or test['result'] == 'NOT TESTED', f'{cid}/{tid}: latest/history disagree')
                # NOT TESTED may invalidate a formerly passing run without erasing that history.
                for h in test['history']:
                    need(h.get('result') in RESULTS and all(h.get(k) for k in ['date', 'revision', 'environment', 'evidence', 'run']), f'{cid}/{tid}: incomplete result provenance')
                    need(bool(h.get('command') if test['kind'] == 'automated' else h.get('steps')), f'{cid}/{tid}: no command/steps recorded')
        if not c['visual']:
            need('No visual reference generation required for this checkpoint.' in brief, f'{cid}: missing nonvisual statement')
            need(not c['reference_requirements'] and not c['gate_a'], f'{cid}: unexpected reference gate')
        else:
            for r in c['reference_requirements']:
                need(r['file'] in brief, f'{cid}: missing exact reference filename')
                need(local(f'review/{cid}/references/{r["folder"]}').is_dir(), f'{cid}: missing save folder')
            if c['status'] in IMPLEMENTATION:
                need(bool(c['gate_a']), f'{cid}: implementation without Gate A')
            if c['gate_a']:
                a = c['gate_a']
                need(all(a.get(k) for k in ['owner_quote', 'date', 'source', 'set_id']), f'{cid}: incomplete Gate A provenance')
                selected = next((s for s in c['reference_sets'] if s['id'] == a['set_id']), None)
                need(bool(selected), f'{cid}: approved reference set missing')
                for reference_set in c['reference_sets']:
                    need(bool(reference_set.get('inspection')), f'{cid}: no recorded image inspection')
                    covered = {f['requirement'] for f in reference_set['files']}
                    need(all(r['file'] in covered for r in c['reference_requirements'] if r['mandatory']), f'{cid}: mandatory reference missing')
                    for f in reference_set['files']:
                        p = local(f['path'])
                        need(f['path'].startswith(f'review/{cid}/references/approved/{reference_set["id"]}/'), f'{cid}: selected path is not immutable set')
                        need(p.is_file(), f'{cid}: selected image missing: {p}')
                        if p.is_file():
                            raw = p.read_bytes()
                            need(hashlib.sha256(raw).hexdigest() == f['sha256'], f'{cid}: selected reference hash changed')
                            need(raw.startswith((b'\x89PNG\r\n\x1a\n', b'\xff\xd8\xff')) or (raw[:4] == b'RIFF' and raw[8:12] == b'WEBP'), f'{cid}: reference header invalid; agent must decode/open it')
        def satisfied(test):
            if test['result'] == 'PASS':
                return True
            # A missing conditional case remains NOT TESTED, with explicit product/owner disposition.
            d = test.get('disposition') or {}
            return (test['result'] == 'NOT TESTED' and test.get('required') is False
                    and all(d.get(k) for k in ['owner_quote', 'date', 'source', 'spec_reference', 'reason']))

        if c['status'] in {'AWAITING OWNER TEST', 'APPROVED'}:
            need(bool(c['latest_run']) and all(t['status'] == 'DONE' for t in c['tasks']), f'{cid}: handoff before work/run complete')
            run = next((r for r in c['runs'] if r['id'] == c['latest_run']), None)
            need(bool(run), f'{cid}: current handoff run not recorded')
            need(all(satisfied(t) for t in c['tests'] if t['kind'] != 'owner'), f'{cid}: engineering gates not passed; resolve scope/limitations explicitly')
        if c['status'] == 'APPROVED':
            b = c['gate_b'] or {}
            need(all(b.get(k) for k in ['owner_quote', 'date', 'source', 'revision', 'run']), f'{cid}: missing Gate B provenance')
            need(all(satisfied(t) for t in c['tests']), f'{cid}: required test not passed; do not silently waive')
            need(b.get('run') == c['latest_run'], f'{cid}: approval run mismatch')
            if run:
                need(b.get('revision') == run.get('revision'), f'{cid}: approved revision differs from handoff')

    # New documentation links, including owner notes, are outside guia.py's inherited scope.
    docs = list((ROOT / 'docs/workflow').rglob('*.md')) + list((ROOT / 'owner').rglob('*.md')) + list((ROOT / 'review').rglob('*.md')) + [ROOT / 'AGENTS.md', ROOT / 'docs/README.md', ROOT / 'README.md']
    for doc in docs:
        for link in re.findall(r'\[[^\]\n]+\]\(([^)]+)\)', doc.read_text()):
            if '://' in link or link.startswith(('#', 'mailto:')):
                continue
            if doc == ROOT / 'README.md' and link.startswith('../../issues/'):
                continue  # Existing GitHub issue-template link is relative to the hosted repository.
            target = (doc.parent / link.split('#', 1)[0]).resolve()
            need(target.exists(), f'{doc.relative_to(ROOT)}: broken link {link}')
    # Enforce only the lightweight tracked-review-media policy; ignored local originals are allowed.
    paths = subprocess.check_output(['git', 'ls-files', '-z', '--', 'review'], cwd=ROOT).decode().split('\0')
    totals = Counter()
    for name in filter(None, paths):
        p = local(name)
        if p.suffix.lower() in {'.png', '.jpg', '.jpeg', '.webp'} and p.exists():
            size = p.stat().st_size
            need(size <= 2 * 1024 * 1024, f'{name}: tracked image exceeds 2 MiB')
            totals[p.parts[len(ROOT.parts) + 1]] += size
    for cid, size in totals.items():
        need(size <= 20 * 1024 * 1024, f'{cid}: tracked media exceeds 20 MiB')
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render', action='store_true', help='Regenerate owner/PROGRESS.md; no approval/status mutation')
    args = parser.parse_args()
    try:
        data = json.loads(RECORD.read_text())
        if args.render:
            (ROOT / 'owner/PROGRESS.md').write_text(overview(data))
        errors = validate(data)
        if (ROOT / 'owner/PROGRESS.md').read_text() != overview(data):
            errors.append('Owner overview stale; run python3 tools/workflow.py --render')
    except (KeyError, TypeError, ValueError, OSError) as error:
        errors = [f'Invalid workflow record: {error}']
    if errors:
        print('\n'.join('FAIL: ' + error for error in errors))
        return 1
    print('PASS: 11 checkpoint records, task/proof IDs, manual-test fields, reference paths, gates, links and owner view are consistent.')
    print('Structural validation only; no product/runtime test or owner approval is implied.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
