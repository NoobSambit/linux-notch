#!/usr/bin/env python3
"""Validate checkpoint records/links; optionally regenerate the owner view. Stdlib only.

This checks record structure and recorded gate prerequisites. It cannot grant owner approval,
decode/review images for an agent, prove a test actually ran, or validate product behavior.
"""
from __future__ import annotations

import argparse
from collections import Counter
from datetime import datetime
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
RECORD = ROOT / 'docs/workflow/progress.json'
STATES = ['PLANNED', 'AWAITING REFERENCES', 'REFERENCES SUBMITTED',
          'AWAITING VISUAL APPROVAL', 'READY TO IMPLEMENT', 'IMPLEMENTING',
          'TESTING', 'AWAITING OWNER TEST', 'APPROVED']
RESULTS = {'PASS', 'FAIL', 'NOT TESTED', 'NEEDS HELP'}
IMPLEMENTATION = set(STATES[4:])
WORKFLOW_STATES = {'AWAITING WORKFLOW APPROVAL', 'IN PROGRESS', 'CHECKPOINTS APPROVED'}


def local(path):
    if not isinstance(path, str) or not path or Path(path).is_absolute() or '..' in Path(path).parts:
        raise ValueError(f'Expected repository-relative path: {path}')
    target = (ROOT / path).resolve()
    if not target.is_relative_to(ROOT):
        raise ValueError(f'Path escapes repository: {path}')
    return target


def overview(data):
    rows = ['# Current progress', '', '<!-- Generated by tools/workflow.py. Edit progress.json, not this view. -->', '',
            '## WHAT YOU NEED TO DO NOW', '']
    records = data['checkpoints']
    selected = data['active_checkpoint'] or data['next_checkpoint']
    current = next((c for c in records if c['id'] == selected), records[-1])
    rows += [current['next_owner_action'], '', f'Workflow: **{data["workflow_status"]}**.',
             f'Active checkpoint: **{data["active_checkpoint"] or "None"}**.',
             (f'Next checkpoint: [{current["id"]}](checkpoints/{current["id"]}.md).' if selected else 'All checkpoints approved; publishing still requires separate permission.'), '',
             '| Checkpoint | State | References | Tasks done | Tests: pass / fail / untested / help |',
             '| --- | --- | --- | --- | --- |']
    for c in records:
        counts = Counter(t['result'] for t in c['tests'])
        ref = 'Not required'
        if c['visual']:
            ref = ('Approved ' + c['gate_a']['set_id'] if c['gate_a'] else
                   'Submitted; awaiting review/approval' if c['status'] in {'REFERENCES SUBMITTED', 'AWAITING VISUAL APPROVAL'} else
                   f'{len(c["reference_requirements"])} images needed when activated; none approved')
        done = sum(t['status'] == 'DONE' for t in c['tasks'])
        score = ' / '.join(str(counts[x]) for x in ['PASS', 'FAIL', 'NOT TESTED', 'NEEDS HELP'])
        rows.append(f'| [{c["id"]} — {c["title"]}](checkpoints/{c["id"]}.md) | {c["status"]} | {ref} | {done}/{len(c["tasks"])} | {score} |')
    rows += ['', '## Current handoff', '', f'- Codex next: {current["next_agent_action"]}',
             f'- You next: {current["next_owner_action"]}',
             f'- Waiting/blocker: {current["blocked_reason"] or "No blocker recorded; follow the next action above."}',
             f'- Test version / run: {current["latest_run"] or "No runtime handoff yet."}', '',
             '## Tests and remaining work', '']
    for c in records:
        if c['id'] != current['id'] and c['status'] == 'PLANNED':
            continue
        rows += [f'### {c["id"]}', '', f'Next: {c["next_owner_action"]}', '',
                 'Remaining tasks: ' + (', '.join(t['id'] for t in c['tasks'] if t['status'] != 'DONE') or 'None') + '.', '']
        owner = [t for t in c['tests'] if t['kind'] == 'owner']
        rows += [f'- **{t["id"]} {t["result"]}** — {t["title"]}' + (f' ({t["reason"]})' if t['reason'] else '') for t in owner]
        rows += ['', 'Engineering checks: ' + '; '.join(f'{t["id"]}: {t["result"]}' for t in c['tests'] if t['kind'] != 'owner') + '.',
                 f'Approval: {"Owner approved the tested run." if c["gate_b"] else "Waiting; no final owner approval recorded."}', '']
    rows += ['Codex keeps this page aligned with its [single progress record](../docs/workflow/progress.json).',
             'An image submission is not visual approval. Automated checks are not app approval.',
             'No image generation is needed for CP-00, CP-01, CP-02 or CP-10.',
             '[Start here](README.md) · [References](VISUAL_REFERENCES.md) · [Testing](TESTING.md) · [Recovery](RECOVERY.md)', '']
    return '\n'.join(rows)


def validate(data, previous=None):
    """Malformed input is a validation failure, including when called by tests."""
    try:
        return _validate(data, previous)
    except (KeyError, TypeError, ValueError, OSError, AttributeError, IndexError,
            subprocess.CalledProcessError) as error:
        return [f'Invalid workflow record: {error}']


def _validate(data, previous):
    errors = []

    def need(condition, message):
        if not condition:
            errors.append(message)

    tracked = set(subprocess.check_output(
        ['git', 'ls-files', '-z'], cwd=ROOT).decode().split('\0'))
    staged_hashes = {}

    def stamp(value, label):
        try:
            parsed = datetime.fromisoformat(value.replace('Z', '+00:00'))
            need(parsed.utcoffset() is not None and parsed.utcoffset().total_seconds() == 0,
                 f'{label}: date must include UTC timezone')
        except (ValueError, TypeError, AttributeError):
            need(False, f'{label}: invalid UTC date')

    def decision(value, label, extra=()):
        need(isinstance(value, dict) and all(isinstance(value.get(k), str) and value[k].strip()
             for k in ('owner_quote', 'date', 'source', *extra)), f'{label}: incomplete owner decision')
        if value:
            stamp(value.get('date'), label)

    def artifact(value, label, prefix='review/'):
        need(isinstance(value, dict), f'{label}: evidence needs path and sha256')
        if not isinstance(value, dict):
            return
        p = local(value['path'])
        name = p.relative_to(ROOT).as_posix()
        need(name.startswith(prefix), f'{label}: evidence outside {prefix}')
        need('/private/' not in name and p.name != '.gitkeep', f'{label}: private/placeholder evidence')
        need(name in tracked, f'{label}: evidence must be tracked (stage reviewed files): {name}')
        need(p.is_file(), f'{label}: evidence missing: {name}')
        if p.is_file():
            need(p.stat().st_size > 0, f'{label}: empty evidence: {name}')
            need(hashlib.sha256(p.read_bytes()).hexdigest() == value.get('sha256'),
                 f'{label}: evidence hash mismatch: {name}')
            if name in tracked:
                if name not in staged_hashes:
                    staged_hashes[name] = hashlib.sha256(subprocess.check_output(
                        ['git', 'show', ':' + name], cwd=ROOT, stderr=subprocess.PIPE)).hexdigest()
                need(staged_hashes[name] == value.get('sha256'),
                     f'{label}: staged evidence differs from recorded hash: {name}')

    def evidence(values, label):
        need(isinstance(values, list) and bool(values), f'{label}: no evidence')
        if isinstance(values, list):
            for value in values:
                artifact(value, label)

    commits = {}

    def commit(value, label):
        if value not in commits:
            commits[value] = bool(isinstance(value, str) and re.fullmatch(r'[0-9a-f]{40}', value)
                                 and subprocess.run(['git', 'cat-file', '-e', value + '^{commit}'],
                                                    cwd=ROOT, capture_output=True).returncode == 0)
        need(commits[value], f'{label}: revision must be a locally available full commit SHA')

    need(type(data['schema_version']) is int and data['schema_version'] == 1, 'Unsupported schema_version')
    need(data['workflow_status'] in WORKFLOW_STATES, 'Invalid workflow_status')
    records = data['checkpoints']
    ids = [c['id'] for c in records]
    need(len(ids) == 11 and len(set(ids)) == 11, 'Expected eleven unique checkpoints')
    need(data['active_checkpoint'] is None or data['active_checkpoint'] in ids, 'Invalid active checkpoint')
    need(data['next_checkpoint'] in ids or (data['next_checkpoint'] is None and all(c['status'] == 'APPROVED' for c in records)), 'Invalid next checkpoint')
    by_id = {c['id']: c for c in records}
    unfinished = [c['id'] for c in records if c['status'] != 'APPROVED']
    active = [c['id'] for c in records if c['status'] not in {'PLANNED', 'APPROVED'}]
    need(len(active) <= 1, 'Only one checkpoint may be active')
    need(data['active_checkpoint'] == (active[0] if active else None), 'Active checkpoint does not match lifecycle')
    need(data['next_checkpoint'] == (unfinished[0] if unfinished else None), 'Next checkpoint must be first incomplete')
    if active:
        need(active[0] == unfinished[0], 'Active checkpoint skips incomplete prerequisites')
    worked = [c['id'] for c in records if c['status'] != 'PLANNED']
    latest_worked = worked[-1] if worked else None
    if data['workflow_status'] == 'AWAITING WORKFLOW APPROVAL':
        need(all(c['status'] == 'PLANNED' and c['authorization'] is None for c in records),
             'Workflow awaiting approval cannot contain authorized/started checkpoints')
    else:
        decision(records[0]['authorization'], 'Workflow/CP-00 authorization', ('scope',))
    need((data['workflow_status'] == 'CHECKPOINTS APPROVED') == (not unfinished),
         'Workflow completion disagrees with checkpoints')
    for i, c in enumerate(records):
        cid = c['id']
        need(cid.startswith(f'cp-{i:02}-'), f'{cid}: roadmap order changed')
        need(c['status'] in STATES, f'{cid}: invalid lifecycle')
        need(type(c['visual']) is bool and c['visual'] == (3 <= i <= 9), f'{cid}: visual classification mismatch')
        need(c['depends_on'] == ([] if i == 0 else [ids[i-1]]), f'{cid}: sequence/dependency changed')
        need(c['visual'] or c['status'] not in STATES[1:4], f'{cid}: nonvisual checkpoint in visual lifecycle')
        if c['authorization']:
            decision(c['authorization'], f'{cid}: authorization', ('scope',))
        if c['status'] != 'PLANNED':
            need(bool(c['authorization']), f'{cid}: authorization missing/incomplete')
            need(all(d in by_id and by_id[d]['status'] == 'APPROVED' and not by_id[d]['blocked_reason']
                     for d in c['depends_on']), f'{cid}: unapproved/blocked dependency')
            need(c['branch'] == f'checkpoint/{cid}', f'{cid}: checkpoint branch missing/mismatched')
            commit(c['last_good_sha'], f'{cid}: last_good_sha')
            if i and by_id[ids[i-1]]['gate_b']:
                need(c['last_good_sha'] == by_id[ids[i-1]]['gate_b']['revision'],
                     f'{cid}: recovery revision differs from accepted predecessor')
        need(bool(c['next_agent_action']) and bool(c['next_owner_action']), f'{cid}: missing resume actions')
        if c['status'] in {'READY TO IMPLEMENT', 'AWAITING OWNER TEST', 'APPROVED'}:
            need(not c['blocked_reason'], f'{cid}: blocked checkpoint cannot be ready/approved')
        need(not c['gate_b'] or c['status'] == 'APPROVED', f'{cid}: stale Gate B outside APPROVED')
        for h in c.get('approval_history', []):
            need(h.get('gate') in {'gate_a', 'gate_b'} and bool(h.get('reason')),
                 f'{cid}: incomplete archived approval')
            stamp(h.get('date'), f'{cid}: approval archive')
            decision(h.get('decision'), f'{cid}: archived decision',
                     ('set_id',) if h.get('gate') == 'gate_a' else ('revision', 'run'))
        if c['status'] == 'PLANNED':
            retained = bool(c.get('approval_history') and c['blocked_reason'] and c['authorization'])
            need(retained or not (c['runs'] or c['reference_sets'] or c['gate_a'] or c.get('submission')
                                  or any(t['history'] for t in c['tests'])),
                 f'{cid}: evidence/approval before activation without suspension history')
            need(all(t['result'] == 'NOT TESTED' for t in c['tests']), f'{cid}: PLANNED results must be untested/invalidated')
        for field in ['contract', 'visual_brief', 'owner_note']:
            need(local(c[field]).is_file(), f'{cid}: missing {field}')
        need(c['contract'] == f'docs/workflow/checkpoints/{cid}.md'
             and c['visual_brief'] == f'docs/workflow/checkpoints/{cid}.visual.md'
             and c['owner_note'] == f'owner/checkpoints/{cid}.md', f'{cid}: mismatched document identity')
        contract = local(c['contract']).read_text()
        brief = local(c['visual_brief']).read_text()
        owner = local(c['owner_note']).read_text()
        for heading in ['Objective', 'Prerequisites', 'Authoritative specification references',
                        'In scope and affected modules', 'Out of scope', 'Implementation tasks',
                        'Acceptance criteria and proof mapping', 'Technical risks',
                        'Automated verification', 'Runtime verification', 'Completion and approval gates']:
            need(f'## {heading}' in contract, f'{cid}: missing contract {heading}')
        need('WHAT YOU NEED TO DO NOW' in owner, f'{cid}: missing owner action')
        task_ids = [t['id'] for t in c['tasks']]
        test_ids = [t['id'] for t in c['tests']]
        need(set(task_ids) == set(re.findall(r'^\| (T\d{2}) \|', contract, re.M)),
             f'{cid}: contract/record task IDs differ')
        declared_tests = set(re.findall(r'^- \*\*([AR]\d{2}(?:-[\w-]+)?):\*\*', contract, re.M))
        declared_tests |= set(re.findall(r'^### (M\d{2}(?:-[\w-]+)?) — ', owner, re.M))
        need(set(test_ids) == declared_tests, f'{cid}: contract/record test IDs differ')
        need(len(set(task_ids)) == len(task_ids), f'{cid}: duplicate tasks')
        need(len(set(test_ids)) == len(test_ids), f'{cid}: duplicate tests')
        proof_ids = set(re.findall(r'\b[ARM]\d{2}\b', contract))
        need(proof_ids.issubset(set(test_ids)), f'{cid}: unknown acceptance/task proof ID')
        for task in c['tasks']:
            need(f'| {task["id"]} |' in contract, f'{cid}: undocumented task')
            need(task['status'] in {'PENDING', 'IN PROGRESS', 'DONE'}, f'{cid}: invalid task state')
            if task['status'] == 'DONE':
                evidence(task['evidence'], f'{cid}/{task["id"]}')
            if task['status'] != 'PENDING':
                preparation = c['visual'] and task['id'] == 'T01' and c['status'] in STATES[1:4]
                suspended = (c['status'] in STATES[:4] and c.get('approval_history')
                             and c['blocked_reason'] and task['status'] == 'DONE')
                need(bool(c['authorization']) and (c['status'] in IMPLEMENTATION or preparation or suspended),
                     f'{cid}/{task["id"]}: work before authorization/lifecycle gate')
        in_progress = [t['id'] for t in c['tasks'] if t['status'] == 'IN PROGRESS']
        need(len(in_progress) <= 1 and c['current_task'] == (in_progress[0] if in_progress else None),
             f'{cid}: current_task does not match task state')
        if c['status'] in {'TESTING', 'AWAITING OWNER TEST', 'APPROVED'}:
            need(all(t['status'] == 'DONE' for t in c['tasks']), f'{cid}: testing before tasks complete')

        run_ids = [r['id'] for r in c['runs']]
        need(len(set(run_ids)) == len(run_ids), f'{cid}: duplicate runs')
        need(c['latest_run'] == (run_ids[-1] if run_ids else None), f'{cid}: latest_run must identify newest run')
        runs = {r['id']: r for r in c['runs']}
        for r in c['runs']:
            need(bool(re.fullmatch(r'run-\d{2,}', r['id'])), f'{cid}: invalid run ID')
            commit(r['revision'], f'{cid}/{r["id"]}')
            stamp(r['date'], f'{cid}/{r["id"]}')
            need(isinstance(r['environment'], str) and bool(r['environment'].strip()), f'{cid}: missing run environment')
            if r.get('patch'):
                artifact(r['patch'], f'{cid}: dirty patch')
            for field in ['handoff', 'review', 'recovery', 'comparison']:
                if field in r:
                    artifact(r[field], f'{cid}/{r["id"]}: retained {field}',
                             f'review/{cid}/evidence/{r["id"]}/')
        for test in c['tests']:
            tid = test['id']
            need(test['result'] in RESULTS, f'{cid}/{tid}: invalid test result')
            need(test['kind'] in {'automated', 'runtime', 'owner'}, f'{cid}/{tid}: invalid test kind')
            need(test['kind'] == {'A': 'automated', 'R': 'runtime', 'M': 'owner'}.get(tid[:1]),
                 f'{cid}/{tid}: test kind differs from ID')
            need(tid in contract, f'{cid}/{tid}: missing engineering proof mapping')
            if test['kind'] == 'owner':
                match = re.search(rf'### {tid} — .*?(?=\n### |\n## |\Z)', owner, re.S)
                need(bool(match), f'{cid}/{tid}: missing owner test')
                if match:
                    for label in ['Before starting', 'What to do', 'Expected result', 'Failure examples', 'Evidence', 'Recovery']:
                        need(f'**{label}:**' in match[0], f'{cid}/{tid}: missing {label}')
                    steps = re.findall(r'^\d+\.\s*([^\n]*)$', match[0], re.M)
                    need(bool(steps) and all(s.strip() for s in steps), f'{cid}/{tid}: empty/missing numbered steps')
            if test['result'] != 'NOT TESTED':
                need(bool(test['history']), f'{cid}/{tid}: result without history')
            if test['history']:
                need(test['history'][-1]['result'] == test['result'] or test['result'] == 'NOT TESTED', f'{cid}/{tid}: latest/history disagree')
                # NOT TESTED may invalidate a formerly passing run without erasing that history.
                for h in test['history']:
                    need(h.get('result') in RESULTS and all(h.get(k) for k in ['date', 'revision', 'environment', 'evidence', 'run']), f'{cid}/{tid}: incomplete result provenance')
                    need(bool(h.get('command') if test['kind'] == 'automated' else h.get('steps')), f'{cid}/{tid}: no command/steps recorded')
                    stamp(h.get('date'), f'{cid}/{tid}')
                    evidence(h.get('evidence'), f'{cid}/{tid}')
                    need(h['run'] in runs, f'{cid}/{tid}: history run missing')
                    if h['run'] in runs:
                        r = runs[h['run']]
                        need(h['revision'] == r['revision'] and h['environment'] == r['environment']
                             and h.get('patch') == r.get('patch'), f'{cid}/{tid}: history/run identity mismatch')
                    if test['kind'] == 'automated':
                        need(type(h.get('exit_code')) is int, f'{cid}/{tid}: missing exit code')
                        need(h['result'] != 'PASS' or h.get('exit_code') == 0, f'{cid}/{tid}: PASS with nonzero exit code')
                    else:
                        need(bool(h.get('observed')), f'{cid}/{tid}: missing observed result')
                if test['result'] != 'NOT TESTED':
                    need(test['history'][-1]['run'] == c['latest_run'], f'{cid}/{tid}: stale result from another run')
            if test['result'] == 'NOT TESTED':
                need(bool(test['reason']), f'{cid}/{tid}: missing untested/invalidation reason')
        if not c['visual']:
            need('No visual reference generation required for this checkpoint.' in brief, f'{cid}: missing nonvisual statement')
            need(not c['reference_requirements'] and not c['gate_a'] and not c['reference_sets'],
                 f'{cid}: unexpected reference gate')
        else:
            slots = re.findall(r'cp-\d{2}__[a-z0-9-]+__(?:dark|light|both)__r01\.png', brief)
            need({r['file'] for r in c['reference_requirements']} == set(slots)
                 and len(c['reference_requirements']) == len(set(slots)) and bool(slots)
                 and all(r['mandatory'] is True for r in c['reference_requirements']),
                 f'{cid}: reference requirements differ from mandatory brief slots')
            for r in c['reference_requirements']:
                need(r['file'] in brief, f'{cid}: missing exact reference filename')
                need(local(f'review/{cid}/references/{r["folder"]}').is_dir(), f'{cid}: missing save folder')
            if c['status'] in IMPLEMENTATION:
                need(bool(c['gate_a']), f'{cid}: implementation without Gate A')
            need(len({s['id'] for s in c['reference_sets']}) == len(c['reference_sets']), f'{cid}: duplicate reference sets')
            # Validate retained sets even while Gate A is reopened.
            for reference_set in c['reference_sets']:
                need(bool(re.fullmatch(r'r\d{2,}', reference_set['id'])), f'{cid}: invalid set ID')
                need(bool(reference_set.get('inspection')), f'{cid}: no recorded image inspection')
                artifact(reference_set['design_spec'], f'{cid}: design translation',
                         f'review/{cid}/references/approved/{reference_set["id"]}/')
                covered = [f['requirement'] for f in reference_set['files']]
                need(len(covered) == len(set(covered)), f'{cid}: duplicate reference slots')
                need(set(covered).issubset({r['file'] for r in c['reference_requirements']}), f'{cid}: unknown reference slot')
                need(all(r['file'] in covered for r in c['reference_requirements'] if r['mandatory']), f'{cid}: mandatory reference missing')
                for f in reference_set['files']:
                    artifact(f, f'{cid}: reference', f'review/{cid}/references/approved/{reference_set["id"]}/')
                    need(bool(f.get('source_path')), f'{cid}: reference source path missing')
                    p = local(f['path'])
                    if p.is_file():
                        raw = p.read_bytes()
                        need(raw.startswith((b'\x89PNG\r\n\x1a\n', b'\xff\xd8\xff')) or (raw[:4] == b'RIFF' and raw[8:12] == b'WEBP'), f'{cid}: reference header invalid; agent must decode/open it')
            if c['status'] in {'REFERENCES SUBMITTED', 'AWAITING VISUAL APPROVAL'}:
                need(bool(c.get('submission')), f'{cid}: submission inventory missing')
                for f in c.get('submission', []):
                    artifact(f, f'{cid}: submitted reference', f'review/{cid}/references/')
                covered = {f['requirement'] for f in c.get('submission', [])}
                need(all(r['file'] in covered for r in c['reference_requirements'] if r['mandatory']), f'{cid}: submission incomplete')
            if c['status'] == 'AWAITING VISUAL APPROVAL':
                artifact(c['proposed_design_spec'], f'{cid}: proposed design translation', f'review/{cid}/references/')
            if c['gate_a']:
                a = c['gate_a']
                decision(a, f'{cid}: Gate A', ('set_id',))
                selected = next((s for s in c['reference_sets'] if s['id'] == a['set_id']), None)
                need(bool(selected), f'{cid}: approved reference set missing')
                if selected:
                    need(a.get('design_spec_sha256') == selected['design_spec']['sha256'], f'{cid}: Gate A design translation mismatch')
        def satisfied(test):
            if test['result'] == 'PASS':
                return True
            # A missing conditional case remains NOT TESTED, with explicit product/owner disposition.
            d = test.get('disposition') or {}
            allowed = (test['result'] == 'NOT TESTED' and test.get('required') is False
                       and all(d.get(k) for k in ['owner_quote', 'date', 'source', 'spec_reference', 'reason']))
            if allowed:
                decision(d, f'{cid}/{test["id"]}: disposition', ('spec_reference', 'reason'))
                need(local(d['spec_reference'].split('#')[0]).is_file(), f'{cid}: disposition specification missing')
                artifact(d['evidence'], f'{cid}: disposition evidence')
            return allowed

        if c['status'] in {'AWAITING OWNER TEST', 'APPROVED'}:
            need(bool(c['latest_run']) and all(t['status'] == 'DONE' for t in c['tasks']), f'{cid}: handoff before work/run complete')
            run = next((r for r in c['runs'] if r['id'] == c['latest_run']), None)
            need(bool(run), f'{cid}: current handoff run not recorded')
            need(all(satisfied(t) for t in c['tests'] if t['kind'] != 'owner'), f'{cid}: engineering gates not passed; resolve scope/limitations explicitly')
        if c['status'] == 'APPROVED':
            b = c['gate_b'] or {}
            need(all(b.get(k) for k in ['owner_quote', 'date', 'source', 'revision', 'run']), f'{cid}: missing Gate B provenance')
            need(all(satisfied(t) for t in c['tests']), f'{cid}: required test not passed; do not silently waive')
            need(b.get('run') == c['latest_run'], f'{cid}: approval run mismatch')
            if run:
                need(b.get('revision') == run.get('revision'), f'{cid}: approved revision differs from handoff')
            decision(b, f'{cid}: Gate B', ('revision', 'run'))
        if c['status'] in {'AWAITING OWNER TEST', 'APPROVED'} and run:
            need(not run.get('patch'), f'{cid}: owner handoff requires a clean committed revision')
            for field in ['handoff', 'review', 'recovery']:
                artifact(run[field], f'{cid}: {field}', f'review/{cid}/evidence/{run["id"]}/')
            if c['visual']:
                artifact(run['comparison'], f'{cid}: comparison', f'review/{cid}/evidence/{run["id"]}/')
                need(run.get('reference_set') == c['gate_a']['set_id'], f'{cid}: run reference set mismatch')
            commit(run['revision'], f'{cid}: tested revision')
            if commits.get(c['last_good_sha']) and commits.get(run['revision']):
                need(subprocess.run(['git', 'merge-base', '--is-ancestor', c['last_good_sha'], run['revision']],
                                    cwd=ROOT, capture_output=True).returncode == 0,
                     f'{cid}: tested revision does not descend from recovery revision')
            if cid == latest_worked and re.fullmatch(r'[0-9a-f]{40}', run['revision']):
                # Progress/evidence commits follow the tested commit. Product changes do not.
                changes = subprocess.check_output(
                    ['git', 'diff', '--name-only', run['revision'], '--'], cwd=ROOT).decode().splitlines()
                changes += subprocess.check_output(
                    ['git', 'ls-files', '--others', '--exclude-standard'], cwd=ROOT).decode().splitlines()
                bookkeeping = ('docs/workflow/', 'owner/', 'review/')
                bookkeeping_files = {'AGENTS.md', '.gitignore', 'README.md', 'docs/README.md',
                                     'tools/workflow.py', 'tools/test_workflow.py'}
                changed_product = [p for p in changes if not p.startswith(bookkeeping) and p not in bookkeeping_files]
                need(not changed_product, f'{cid}: product differs from tested revision: {", ".join(changed_product[:5])}')

    # New documentation links, including owner notes, are outside guia.py's inherited scope.
    docs = list((ROOT / 'docs/workflow').rglob('*.md')) + list((ROOT / 'owner').rglob('*.md')) + list((ROOT / 'review').rglob('*.md')) + [ROOT / 'AGENTS.md', ROOT / 'docs/README.md', ROOT / 'README.md']
    for doc in docs:
        for link in re.findall(r'\[[^\]\n]+\]\(([^)]+)\)', doc.read_text()):
            if '://' in link or link.startswith(('#', 'mailto:')):
                continue
            if doc == ROOT / 'README.md' and link.startswith('../../issues/'):
                continue  # Existing GitHub issue-template link is relative to the hosted repository.
            target = (doc.parent / link.split('#', 1)[0]).resolve()
            need(target.exists(), f'{doc.relative_to(ROOT)}: broken link {link}')
    # Enforce only the lightweight tracked-review-media policy; ignored local originals are allowed.
    paths = [p for p in tracked if p.startswith('review/')]
    totals = Counter()
    for name in filter(None, paths):
        p = local(name)
        if p.suffix.lower() in {'.png', '.jpg', '.jpeg', '.webp'} and p.exists():
            size = p.stat().st_size
            need(size <= 2 * 1024 * 1024, f'{name}: tracked image exceeds 2 MiB')
            totals[p.parts[len(ROOT.parts) + 1]] += size
    for cid, size in totals.items():
        need(size <= 20 * 1024 * 1024, f'{cid}: tracked media exceeds 20 MiB')
    if previous:
        errors.extend(validate_history(data, previous))
    return errors


def validate_history(data, previous):
    """Compare with a Git base: preserve evidence and decisions, allow explicit invalidation."""
    errors = []
    current = {c['id']: c for c in data['checkpoints']}

    def prefix(old, new, label):
        if new[:len(old)] != old:
            errors.append(f'{label}: append-only history changed/removed')

    for old in previous['checkpoints']:
        cid = old['id']
        if cid not in current:
            errors.append(f'{cid}: checkpoint removed')
            continue
        new = current[cid]
        for field in ['runs', 'reference_sets', 'approval_history']:
            prefix(old.get(field, []), new.get(field, []), f'{cid}/{field}')
        for gate in ['gate_a', 'gate_b']:
            if old.get(gate) and old[gate] != new.get(gate):
                if not any(h.get('gate') == gate and h.get('decision') == old[gate]
                           and h.get('reason') and h.get('date') for h in new.get('approval_history', [])):
                    errors.append(f'{cid}: superseded {gate} must be archived with reason/date')
        if old['authorization'] and old['authorization'] != new['authorization']:
            errors.append(f'{cid}: authorization cannot be rewritten')
        for field, history in [('tests', 'history'), ('tasks', 'evidence')]:
            updated = {t['id']: t for t in new[field]}
            for t in old[field]:
                if t['id'] not in updated:
                    errors.append(f'{cid}/{t["id"]}: declared {field} removed')
                else:
                    prefix(t[history], updated[t['id']][history], f'{cid}/{t["id"]}/{history}')
    return errors


def read_base(ref):
    sha = subprocess.check_output(['git', 'rev-parse', '--verify', '--end-of-options',
                                   ref + '^{commit}'], cwd=ROOT, stderr=subprocess.PIPE).decode().strip()
    path = RECORD.relative_to(ROOT).as_posix()
    if not subprocess.check_output(['git', 'ls-tree', sha, '--', path], cwd=ROOT).strip():
        return None  # First introduction of the workflow on this branch.
    return json.loads(subprocess.check_output(['git', 'show', sha + ':' + path], cwd=ROOT))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render', action='store_true', help='Regenerate owner/PROGRESS.md; no approval/status mutation')
    parser.add_argument('--base-ref', help='Git base SHA/ref for append-only history validation')
    args = parser.parse_args()
    try:
        data = json.loads(RECORD.read_text())
        errors = validate(data, read_base(args.base_ref) if args.base_ref else None)
        if args.render and not errors:
            (ROOT / 'owner/PROGRESS.md').write_text(overview(data))
        if not errors and (ROOT / 'owner/PROGRESS.md').read_text() != overview(data):
            errors.append('Owner overview stale; run python3 tools/workflow.py --render')
    except (KeyError, TypeError, ValueError, OSError, subprocess.CalledProcessError) as error:
        errors = [f'Invalid workflow record: {error}']
    if errors:
        print('\n'.join('FAIL: ' + error for error in errors))
        return 1
    print('PASS: 11 checkpoint records, task/proof IDs, manual-test fields, reference paths, gates, links and owner view are consistent.')
    print('Structural validation only; no product/runtime test or owner approval is implied.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
